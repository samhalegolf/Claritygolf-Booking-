// Writes the numbers Xcode and Gradle stamp into the app bundles.
//
// Two values, two different sources, for two different audiences:
//
//   iOS                      Android        source
//   MARKETING_VERSION        versionName    package.json "version"   what a player sees
//   CURRENT_PROJECT_VERSION  versionCode    git commit count         what the stores use
//                                                                    to tell uploads apart
//
// App Store Connect and Google Play both reject an upload whose build number
// is not higher than the last one for that app. A commit count is monotonic for any normal
// history and maps a build straight back to a commit, which is what you want
// when a tester reports something against "build 214".
//
// Two apps share this script and this repo, so they share the commit count:
//
//   node scripts/sync-app-version.mjs               the Player app (source/)
//   node scripts/sync-app-version.mjs booking-app   the staff app (source/booking-app/)
//
// Each app has its own bundle id, so the stores never compare one app's number
// with the other's, and the files in releases/ carry the app's name as well as
// the number, so they cannot be mistaken for each other on disk.
//
// Building the SAME commit twice gives the same number, which the second
// upload would be refused for. Commit first, or override for one build:
//
//   BUILD_NUMBER=1300 npm run native:release:aab
//
// The output is generated, gitignored, and rewritten before every native
// build. Nothing here is a source of truth -- bump the app's package.json to
// change the marketing version, and the build number takes care of itself.

import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

/** The app folder: source/ itself, or a sub-folder such as booking-app. */
export function resolveAppDir(arg) {
  const dir = path.resolve(ROOT, arg || ".");
  if (!existsSync(path.join(dir, "package.json"))) {
    throw new Error(`No package.json in ${dir}, so this is not an app folder.`);
  }
  return dir;
}

/**
 * Commits reachable from HEAD, or BUILD_NUMBER when set.
 *
 * A shallow clone (CI often does `--depth 1`) counts 1, which would hand App
 * Store Connect a build number below every previous upload. Better to stop
 * with an explanation than to ship a number that gets rejected on upload, or
 * worse, silently overwrites the wrong build.
 */
export function buildNumber() {
  const override = process.env.BUILD_NUMBER;
  if (override !== undefined && override !== "") {
    if (!/^\d+$/.test(override) || Number(override) < 1) {
      throw new Error(`BUILD_NUMBER must be a whole number above zero, got "${override}".`);
    }
    return Number(override);
  }
  const count = Number(
    execFileSync("git", ["rev-list", "--count", "HEAD"], {
      cwd: ROOT,
      encoding: "utf8",
    }).trim(),
  );
  if (!Number.isInteger(count) || count < 1) {
    throw new Error("Could not count commits. Is this a git checkout?");
  }
  const shallow = execFileSync("git", ["rev-parse", "--is-shallow-repository"], {
    cwd: ROOT,
    encoding: "utf8",
  }).trim();
  if (shallow === "true") {
    throw new Error(
      "This is a shallow clone, so the commit count is not the real one and " +
        "the build number would go backwards. Fetch full history first:\n" +
        "  git fetch --unshallow",
    );
  }
  return count;
}

/**
 * CFBundleShortVersionString is one to three dot-separated integers and
 * nothing else -- no "-beta.1", no "+build". Take the numeric head of whatever
 * package.json says so a prerelease tag there cannot fail an upload here.
 */
export function marketingVersion(appDir) {
  const raw = JSON.parse(readFileSync(path.join(appDir, "package.json"), "utf8")).version ?? "";
  const match = /^\d+(\.\d+){0,2}/.exec(String(raw));
  if (!match) throw new Error(`package.json version "${raw}" is not a version Apple accepts.`);
  return match[0];
}

/* For the console line. The Player app's package is confusingly named
   "clarity-booking", so say which app this is in words. */
export function appName(appDir) {
  const rel = path.relative(ROOT, appDir) || ".";
  if (rel === ".") return "Clarity Player";
  if (rel === "booking-app") return "Clarity Booking (staff app)";
  return JSON.parse(readFileSync(path.join(appDir, "package.json"), "utf8")).name ?? rel;
}

export function writeVersionFiles(appDir) {
  const build = buildNumber();
  const marketing = marketingVersion(appDir);
  const xcconfig = path.join(appDir, "ios/App/App/Version.xcconfig");
  const androidVersion = path.join(appDir, "android/app/version.properties");

  writeFileSync(
    xcconfig,
    [
      "// Generated by scripts/sync-app-version.mjs before every native build.",
      "// Do not edit, and do not commit: it is in .gitignore for a reason.",
      "//",
      "// MARKETING_VERSION comes from package.json. CURRENT_PROJECT_VERSION is the",
      "// commit count, so build N is always the Nth commit.",
      `MARKETING_VERSION = ${marketing}`,
      `CURRENT_PROJECT_VERSION = ${build}`,
      "",
    ].join("\n"),
  );

  writeFileSync(
    androidVersion,
    [
      "# Generated by scripts/sync-app-version.mjs before every native build.",
      "# Do not edit, and do not commit: it is in .gitignore for a reason.",
      `VERSION_NAME=${marketing}`,
      `VERSION_CODE=${build}`,
      "",
    ].join("\n"),
  );

  return { build, marketing };
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const appDir = resolveAppDir(process.argv[2]);
  const { build, marketing } = writeVersionFiles(appDir);
  const source = process.env.BUILD_NUMBER ? "BUILD_NUMBER" : "commit count";
  console.log(`${appName(appDir)} version ${marketing} (build ${build}, from ${source})`);
}
